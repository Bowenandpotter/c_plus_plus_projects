// 现有 2^n×2^n
//  (n≤10) 名作弊者站成一个正方形方阵等候 kkksc03 的发落。
// kkksc03 决定赦免一些作弊者。他将正方形矩阵均分为 4 个更小的正方形矩阵，每个更小的矩阵的边长是原矩阵的一半。
// 其中左上角那一个矩阵的所有作弊者都将得到赦免，剩下 3 个小矩阵中，每一个矩阵继续分为 4 个更小的矩阵，然后通过同样的方式赦免作弊者……直到矩阵无法再分下去为止。
// 所有没有被赦免的作弊者都将被处以棕名处罚。
// 给出 n，请输出每名作弊者的命运，其中 0 代表被赦免，1 代表不被赦免。

#include<iostream>
using namespace std;

int main()
{
    int n;
    cin>>n;
    int a[1200][1200]={};
    a[0][0]=1;
    int i,j,k,s=1;
    for(i=0;i<n;i++,s*=2)
    {
        for(j=0;j<s;j++)
        {
            for(k=0;k<s;k++)
            {
                a[j][k+s]=a[j][k];
                a[k+s][j]=a[j][k];
            }
        }
    }
    for(int p=s-1;p>=0;p--)
    {
        for(int m=s-1;m>=0;m--)
        {
            cout<<a[p][m]<<' ';
        }
        cout<<endl;
    }
    return 0;
}